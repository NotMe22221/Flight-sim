/** Every `SimAction`, in declaration order. */
export const SIM_ACTIONS = Object.keys(SIM_ACTION_META) as SimAction[];
/** Every input-local action. */
export const LOCAL_ACTIONS = Object.keys(LOCAL_ACTION_META) as LocalAction[];

/** Every `SimAxis`, typed as a full Record so new axes fail to compile until listed. */
const AXIS_TITLES: Record<SimAxis, string> = {
  pitch: 'Elevator', roll: 'Ailerons', yaw: 'Rudder', throttle: 'Throttle', mixture: 'Mixture',
  propeller: 'Propeller', brakeLeft: 'Left brake', brakeRight: 'Right brake',
  lookYaw: 'Look left/right', lookPitch: 'Look up/down', cameraZoom: 'Camera zoom',
};
export const SIM_AXES = Object.keys(AXIS_TITLES) as SimAxis[];

/** Axes that hold their value (levers) rather than returning to centre. */
export const LEVER_AXES: ReadonlySet<SimAxis> = new Set<SimAxis>(['throttle', 'mixture', 'propeller']);

const SIM_ACTION_SET: ReadonlySet<string> = new Set(SIM_ACTIONS);
const LOCAL_ACTION_SET: ReadonlySet<string> = new Set(LOCAL_ACTIONS);
const SIM_AXIS_SET: ReadonlySet<string> = new Set(SIM_AXES);

export const isSimAction = (a: string): a is SimAction => SIM_ACTION_SET.has(a);
export const isLocalAction = (a: string): a is LocalAction => LOCAL_ACTION_SET.has(a);
export const isBindableAction = (a: string): a is BindableAction => SIM_ACTION_SET.has(a) || LOCAL_ACTION_SET.has(a);
export const isSimAxis = (a: string): a is SimAxis => SIM_AXIS_SET.has(a);

/** Metadata for any bindable action. */
export function actionMeta(a: BindableAction): ActionMeta {
  return isSimAction(a) ? SIM_ACTION_META[a] : LOCAL_ACTION_META[a];
}

/** Human title for an axis direction, e.g. ('pitch', -1) → "Elevator −". */
export function axisTitle(axis: SimAxis, dir?: number): string {
  const t = AXIS_TITLES[axis];
  if (dir === undefined || dir === 0) return t;
  return `${t} ${dir > 0 ? '+' : '−'}`;
}

/** Number of SimAxes (size of per-axis typed arrays). */
export const AXIS_COUNT = SIM_AXES.length;
const AXIS_INDEX = Object.fromEntries(SIM_AXES.map((a, i) => [a, i])) as Record<SimAxis, number>;
/** Stable index of an axis in per-axis typed arrays. */
export const axisIndexOf = (a: SimAxis): number => AXIS_INDEX[a];

/** Output range of an axis: levers and brakes are 0..1, the rest −1..1. */
export function axisRange(a: SimAxis): [number, number] {
  return LEVER_AXES.has(a) || a === 'brakeLeft' || a === 'brakeRight' ? [0, 1] : [-1, 1];
}
