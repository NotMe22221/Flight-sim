/**
 * Action metadata for the input module: which group an action belongs to (for the
 * controls page), whether it auto-repeats while held, whether it is a level ("held")
 * action, plus the input-local actions that are not (yet) part of `SimAction`.
 */
import type { SimAction, SimAxis } from '../core/types';

/**
 * Actions handled entirely inside the input module. They are bindable like any
 * `SimAction` but never appear in `InputSnapshot.actions`.
 * (Proposed for inclusion in `SimAction`; see README "Proposed contract changes".)
 */
export type LocalAction =
  | 'mouseYokeToggle' | 'freeLookToggle' | 'centerControls'
  | 'propellerLow' | 'propellerDec' | 'propellerInc' | 'propellerHigh'
  | 'spoilersToggle';

/** Anything a key / button can be bound to. */
export type BindableAction = SimAction | LocalAction;

/** Display group used by the controls page and the help sheet. */
export type ActionGroup =
  | 'Flight controls' | 'Trim' | 'Engine' | 'Flaps, gear & brakes' | 'Lights' | 'Autopilot'
  | 'Radios & instruments' | 'Camera' | 'Simulation' | 'ATC' | 'Interface';

/** Auto-repeat class: `none` = edge only; `step` = 10 Hz after 300 ms; `knob` = like step, accelerating after 1 s. */
export type RepeatKind = 'none' | 'step' | 'knob';

export interface ActionMeta {
  group: ActionGroup;
  /** human readable name, e.g. "Flaps down one notch" */
  title: string;
  /** auto-repeat while held (generated by poll(dt), never by OS key repeat) */
  repeat: RepeatKind;
  /** level action: populates `InputSnapshot.held` and is meaningful while held (brakes, starter) */
  held: boolean;
}

const m = (group: ActionGroup, title: string, repeat: RepeatKind = 'none', held = false): ActionMeta =>
  ({ group, title, repeat, held });

